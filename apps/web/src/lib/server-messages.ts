const fallback = "تعذّر إكمال العملية. حاول مرة أخرى، وإذا تكرر الخطأ تواصل مع المشرف.";

// In Arabic, a known message is translated and anything else becomes a general Arabic sentence.
export function localizeError(message: string | null | undefined, arabic: boolean) {
  const text = (message ?? "").trim();
  if (!arabic || !text) return text;
  if (/[؀-ۿ]/.test(text)) return text;
  return ar[text] ?? ar[text.replace(/\.$/, "")] ?? fallback;
}
